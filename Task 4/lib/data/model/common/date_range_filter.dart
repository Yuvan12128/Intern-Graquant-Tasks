class DateRangeFilter {
  String? startDate;
  String? endDate;

  String? get getStartDate {
    return startDate;
  }

  set setStartDate(String? startDate) {
    this.startDate = startDate;
  }

  String? get getEndDate {
    return endDate;
  }

  set setEndDate(String? endDate) {
    this.endDate = endDate;
  }
}
