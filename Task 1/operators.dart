void main() {
  //Arithmetic Operators
  int a = 10, b = 20;
  print(a + b);
  print(a - b);
  print(a * b);
  print(a / b);
  print(a % b);
  print('');
  //Relational Operators
  int age = 18;
  print(age == 18);
  print(age != 18);

  //Logical Operators
  bool isStudent = true;
  bool isAdult = false;
  print(isStudent && isAdult);
  print(isStudent || isAdult);
  print(!isStudent);
}
